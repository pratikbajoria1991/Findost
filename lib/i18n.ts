/**
 * Language support — English + top 10 Indian languages.
 * UI strings for the chat, localized disclaimers appended to answers, and
 * script-range detection for typed queries.
 */

export type Lang =
  | "en" | "hi" | "bn" | "mr" | "te" | "ta" | "gu" | "ur" | "kn" | "or" | "ml";

export const LANGS: { code: Lang; native: string; english: string }[] = [
  { code: "en", native: "English", english: "English" },
  { code: "hi", native: "हिन्दी", english: "Hindi" },
  { code: "bn", native: "বাংলা", english: "Bengali" },
  { code: "mr", native: "मराठी", english: "Marathi" },
  { code: "te", native: "తెలుగు", english: "Telugu" },
  { code: "ta", native: "தமிழ்", english: "Tamil" },
  { code: "gu", native: "ગુજરાતી", english: "Gujarati" },
  { code: "ur", native: "اردو", english: "Urdu" },
  { code: "kn", native: "ಕನ್ನಡ", english: "Kannada" },
  { code: "or", native: "ଓଡ଼ିଆ", english: "Odia" },
  { code: "ml", native: "മലയാളം", english: "Malayalam" },
];

export function isLang(v: unknown): v is Lang {
  return typeof v === "string" && LANGS.some((l) => l.code === v);
}

/** Detect language from script when the user types in an Indic script. */
export function detectScriptLang(text: string): Lang | null {
  if (/[ঀ-৿]/.test(text)) return "bn";
  if (/[ఀ-౿]/.test(text)) return "te";
  if (/[஀-௿]/.test(text)) return "ta";
  if (/[઀-૿]/.test(text)) return "gu";
  if (/[ಀ-೿]/.test(text)) return "kn";
  if (/[଀-୿]/.test(text)) return "or";
  if (/[ഀ-ൿ]/.test(text)) return "ml";
  if (/[؀-ۿ]/.test(text)) return "ur";
  if (/[ऀ-ॿ]/.test(text)) return "hi"; // Devanagari (hi/mr — defaults to hi)
  return null;
}

